#!/usr/bin/env python3
"""
Turn the geocoder's output into SQL for a human to review and run.

Writes nothing to the database. Deliberately conservative:

  * Only ever fills coordinates that are currently NULL. The WHERE clause
    re-checks that, so running this twice cannot move a listing that has since
    been corrected by hand.
  * Refuses to emit a row whose coordinates are outside the plausible range.
  * Records precision. A pin at a city centroid is not the same claim as a pin
    at a street door, and the site says which it is — so the data has to carry
    the distinction rather than the renderer guessing from coincidences.
  * Batched, with a transaction and a verification SELECT at the end.
"""
import json, sys, collections

SRC = sys.argv[1] if len(sys.argv) > 1 else "/tmp/zoigeo/geocoded.json"
OUT = sys.argv[2] if len(sys.argv) > 2 else "supabase/migrations/0002_geocode_backfill.sql"
BATCH = 500

def esc(s):
    return "'" + str(s).replace("'", "''") + "'"

rows = json.load(open(SRC, encoding="utf-8"))
seen, clean, rejected = set(), [], collections.Counter()
for r in rows:
    s = r.get("slug")
    if not s or s in seen:
        rejected["duplicate slug"] += 1; continue
    lat, lng = r.get("lat"), r.get("lng")
    if lat is None or lng is None:
        rejected["no coordinate"] += 1; continue
    if not (-90 <= lat <= 90 and -180 <= lng <= 180):
        rejected["out of range"] += 1; continue
    if abs(lat) < 0.01 and abs(lng) < 0.01:
        # 0,0 is the Gulf of Guinea and is almost always a geocoder failure
        rejected["null island"] += 1; continue
    seen.add(s)
    clean.append({"slug": s, "lat": round(float(lat), 6), "lng": round(float(lng), 6),
                  "precision": r.get("precision") or "city"})

by_prec = collections.Counter(c["precision"] for c in clean)
head = f"""-- Coordinate backfill for zoi.listings
--
-- {len(clean)} listings that currently have no coordinates, geocoded from the
-- address already stored on the record.
--
--   street precision : {by_prec.get('street', 0)}
--   city precision   : {by_prec.get('city', 0)}
--
-- Source: OpenStreetMap via Photon and Nominatim. Every street-level result was
-- validated against the city the listing claims to be in and rejected if it
-- landed more than 40km away, because a confidently wrong pin is worse than no
-- pin. Rejected rows fell back to the city centroid and are marked as such.
--
-- SAFETY
--   * Only fills coordinates that are NULL right now. Re-running is a no-op for
--     anything already set, including anything you have since fixed by hand.
--   * Wrapped in a transaction. Review the counts it prints before COMMIT.
--   * Writes geo precision into profile so the site can keep telling the truth
--     about which pins are a street door and which are a city centre. The
--     jsonb || merge preserves every other key in profile.
--
-- Generated by tools/emit-geocode-sql.py — do not hand-edit.

BEGIN;

CREATE TEMP TABLE _geo (
  slug      text primary key,
  lat       double precision not null,
  lng       double precision not null,
  precision text not null
) ON COMMIT DROP;

"""

parts = [head]
for i in range(0, len(clean), BATCH):
    chunk = clean[i:i + BATCH]
    parts.append("INSERT INTO _geo (slug, lat, lng, precision) VALUES\n")
    parts.append(",\n".join(
        f"  ({esc(c['slug'])},{c['lat']},{c['lng']},{esc(c['precision'])})" for c in chunk))
    parts.append(";\n\n")

parts.append("""-- What will change, before anything changes.
SELECT g.precision, count(*) AS will_update
FROM _geo g
JOIN zoi.listings l ON l.slug = g.slug
WHERE l.latitude IS NULL OR l.longitude IS NULL
GROUP BY g.precision
ORDER BY g.precision;

-- Rows in the file that match no listing (expected to be 0).
SELECT count(*) AS unmatched_slugs
FROM _geo g
WHERE NOT EXISTS (SELECT 1 FROM zoi.listings l WHERE l.slug = g.slug);

UPDATE zoi.listings l
SET latitude  = g.lat,
    longitude = g.lng,
    profile   = coalesce(l.profile, '{}'::jsonb) || jsonb_build_object(
                  '_geo', jsonb_build_object(
                    'precision', g.precision,
                    'source',    'openstreetmap',
                    'method',    CASE WHEN g.precision = 'street'
                                      THEN 'address geocode, validated against city'
                                      ELSE 'city centroid' END,
                    'geocoded_at', to_char(now(), 'YYYY-MM-DD')
                  ))
FROM _geo g
WHERE l.slug = g.slug
  AND (l.latitude IS NULL OR l.longitude IS NULL);

-- Coverage afterwards.
SELECT count(*) FILTER (WHERE latitude IS NOT NULL AND longitude IS NOT NULL) AS with_coords,
       count(*)                                                               AS total,
       round(100.0 * count(*) FILTER (WHERE latitude IS NOT NULL AND longitude IS NOT NULL)
             / nullif(count(*), 0), 1)                                        AS pct
FROM zoi.listings;

-- Review the numbers above, then:
--   COMMIT;
-- or, if anything looks wrong:
--   ROLLBACK;
""")

open(OUT, "w", encoding="utf-8").write("".join(parts))
print(f"wrote {OUT}")
print(f"  rows emitted: {len(clean)}   ({dict(by_prec)})")
if rejected: print(f"  rejected: {dict(rejected)}")
