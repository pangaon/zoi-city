#!/usr/bin/env python3
"""
Turn tools/enrich.py output into reviewable SQL.

Writes into profile._enrich only, so it can never overwrite anything an owner
typed. Every field keeps its provenance, and the batch is applied through
zoi.enrich_apply so there is one audited path rather than ad-hoc UPDATEs.
"""
import json, sys, collections

SRC = sys.argv[1] if len(sys.argv) > 1 else "/tmp/zoigeo/enriched.jsonl"
OUT = sys.argv[2] if len(sys.argv) > 2 else "supabase/migrations/0004_enrich_backfill.sql"
BATCH = 200

rows, stats, dropped = [], collections.Counter(), collections.Counter()
for line in open(SRC, encoding="utf-8"):
    try:
        r = json.loads(line)
    except Exception:
        continue
    if r.get("error"):
        dropped["fetch:" + r["error"][:20]] += 1
        continue
    prof = r.get("profile") or {}
    prov = r.get("provenance") or {}
    if r.get("aggregator"):
        # A directory page is not the business's own site: keep the contact
        # details it lists, discard its branding and imagery.
        for k in ("tagline", "description", "photo_url"):
            prof.pop(k, None); prov.pop(k, None)
        dropped["branding from aggregator"] += 1
    # A photo must be a real absolute URL or it is worse than nothing.
    pu = prof.get("photo_url")
    if pu and not (isinstance(pu, str) and pu.startswith("https://")):
        prof.pop("photo_url", None); prov.pop("photo_url", None)
        dropped["photo not https"] += 1
    if not prof:
        dropped["nothing usable"] += 1
        continue
    for k in prof:
        stats[k] += 1
    rows.append({"slug": r["slug"], "website": r.get("website"),
                 "profile": prof, "provenance": prov})

def lit(o):
    return "'" + json.dumps(o, ensure_ascii=False).replace("'", "''") + "'::jsonb"

head = f"""-- Website enrichment backfill
--
-- {len(rows)} listings enriched from the website each one already links to.
--
-- Field yield:
{chr(10).join(f'--   {k:16} {v}' for k, v in stats.most_common())}
--
-- Everything lands in profile._enrich, never at the top level, so it cannot
-- overwrite a single thing an owner has typed. Each field records where it came
-- from (schema.org JSON-LD, OpenGraph, a tel: link, a page link), so a page can
-- say "hours from their own website, checked today" instead of implying we know
-- something we do not.
--
-- Requires 0003_profile_writable.sql (zoi.enrich_apply).
--
-- Generated by tools/emit-enrich-sql.py — do not hand-edit.

BEGIN;

"""
parts = [head]
for i in range(0, len(rows), BATCH):
    chunk = rows[i:i + BATCH]
    parts.append(f"-- batch {i // BATCH + 1}\nSELECT count(*) AS applied FROM zoi.enrich_apply(\n  ")
    parts.append(lit(chunk))
    parts.append("\n);\n\n")

parts.append("""-- What landed.
SELECT count(*) FILTER (WHERE profile ? '_enrich')                     AS enriched,
       count(*) FILTER (WHERE profile -> '_enrich' ? 'photo_url')      AS with_photo,
       count(*) FILTER (WHERE profile -> '_enrich' ? 'social')         AS with_social,
       count(*) FILTER (WHERE profile -> '_enrich' ? 'description')    AS with_description,
       count(*)                                                       AS total
FROM zoi.listings;

-- Review, then:
--   COMMIT;
-- or:
--   ROLLBACK;
""")
open(OUT, "w", encoding="utf-8").write("".join(parts))
print(f"wrote {OUT}")
print(f"  listings: {len(rows)}")
print(f"  fields:   {dict(stats.most_common())}")
print(f"  dropped:  {dict(dropped.most_common())}")
